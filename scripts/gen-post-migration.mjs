// Generates a PocketBase migration that seeds blog posts from the bundled data, so the
// repo copy and the CMS cannot drift. Mirrors the shape of
// docker/pocketbase/pb_migrations/1747000004_seed_more_posts.js:
//   up   — insert each post unless its slug already exists (idempotent)
//   down — delete exactly the slugs this migration introduced
//
//   node scripts/gen-post-migration.mjs <unix-prefix> <name> <slug,slug,...>
//
// Example:
//   node scripts/gen-post-migration.mjs 1747000005 seed_b2b_webinar_posts a-slug,b-slug
//
// Migrations target the PocketBase 0.22.x JS API (Dao/Record), like the existing ones.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const DATA = join(HERE, '..', 'src', 'data');
const MIGRATIONS = join(HERE, '..', 'docker', 'pocketbase', 'pb_migrations');

const [prefix, name, slugList] = process.argv.slice(2);
if (!prefix || !name || !slugList) {
  throw new Error(
    'usage: node scripts/gen-post-migration.mjs <unix-prefix> <name> <slug,slug,...>',
  );
}

const posts = JSON.parse(readFileSync(join(DATA, 'new-posts.json'), 'utf8'));
const translations = JSON.parse(readFileSync(join(DATA, 'post-translations.json'), 'utf8'));

const wanted = slugList.split(',');
const selected = wanted.map((slug) => {
  const p = posts.find((q) => q.slug === slug);
  if (!p) throw new Error(`slug not found in new-posts.json: ${slug}`);
  return {
    slug: p.slug,
    title: p.title,
    excerpt: p.excerpt,
    content: p.content,
    author: p.author,
    // PocketBase's date format: the bundled data uses ISO with a T separator.
    published_at: p.published_at.replace('T', ' ').replace(/\.\d+Z$/, '.000Z'),
    tags: p.tags,
    i18n: translations[p.slug] ?? null,
  };
});

const missingTranslations = selected.filter((p) => !p.i18n).map((p) => p.slug);
if (missingTranslations.length) {
  console.warn(`warning: no translations for ${missingTranslations.join(', ')}`);
}

const file = `/// <reference path="../pb_data/types.d.ts" />

// Seed ${selected.length} blog posts (English base + it/es/de/fr translations in the i18n
// field). One record per post — no per-language duplicates.
// AUTO-GENERATED by scripts/gen-post-migration.mjs from src/data/new-posts.json +
// post-translations.json — regenerate rather than editing by hand.
migrate(
  (db) => {
    const dao = new Dao(db);
    const collection = dao.findCollectionByNameOrId('posts');
    const POSTS = ${JSON.stringify(selected, null, 2)};
    for (const p of POSTS) {
      // Idempotent: never duplicate a slug that is already in the collection.
      let existing = null;
      try { existing = dao.findFirstRecordByFilter('posts', \`slug = "\${p.slug}"\`); } catch (e) {}
      if (existing) continue;
      const r = new Record(collection);
      r.set('title', p.title);
      r.set('slug', p.slug);
      r.set('excerpt', p.excerpt);
      r.set('content', p.content);
      r.set('author', p.author);
      r.set('published_at', p.published_at);
      r.set('lang', 'en');
      r.set('tags', p.tags);
      r.set('published', true);
      r.set('i18n', p.i18n);
      dao.saveRecord(r);
    }
  },
  (db) => {
    const dao = new Dao(db);
    const slugs = ${JSON.stringify(selected.map((p) => p.slug))};
    for (const s of slugs) {
      try { const r = dao.findFirstRecordByFilter('posts', \`slug = "\${s}"\`); if (r) dao.deleteRecord(r); } catch (e) {}
    }
  },
);
`;

const out = join(MIGRATIONS, `${prefix}_${name}.js`);
writeFileSync(out, file);
console.log(`wrote ${out}`);
console.log(`${selected.length} posts: ${selected.map((p) => p.slug).join(', ')}`);
